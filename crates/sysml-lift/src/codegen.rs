fn emit_rust_requirement_def(r: &RequirementDef, out: &mut String) {
    let rname = to_pascal_ident(&r.name);
    emit_doc_comments(&r.doc, "    ", out);
    let mut args = Vec::new();
    if r.is_abstract {
        args.push("abstract".to_string());
    }
    if let Some(short) = &r.short_name {
        args.push(format!("id = \"{}\"", escape_rust_str(short)));
    }
    if args.is_empty() {
        let _ = writeln!(out, "    #[sysml::requirement]");
    } else {
        let _ = writeln!(out, "    #[sysml::requirement({})]", args.join(", "));
    }
    if rname != r.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&r.name));
    }
    if !r.specializes.is_empty() {
        let specs = r
            .specializes
            .iter()
            .map(|sp| to_pascal_ident(sp.rsplit("::").next().unwrap_or(sp)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    #[sysml::specializes({specs})]");
    }
    if let Some(rat) = &r.rationale {
        let _ = writeln!(out, "    #[sysml::rationale(\"{}\")]", escape_rust_str(rat));
    }
    if let Some(subj) = &r.subject {
        let st = to_pascal_ident(subj.type_name.rsplit("::").next().unwrap_or(&subj.type_name));
        let _ = writeln!(
            out,
            "    #[sysml::subject(name = \"{}\", ty = {st})]",
            escape_rust_str(&subj.name)
        );
    }
    for c in &r.assume_constraints {
        let _ = writeln!(
            out,
            "    #[sysml::assume_constraint(\"{}\")]",
            escape_rust_str(c)
        );
    }
    for c in &r.require_constraints {
        let _ = writeln!(
            out,
            "    #[sysml::require_constraint(\"{}\")]",
            escape_rust_str(c)
        );
    }
    for rf in &r.refinements {
        let _ = writeln!(
            out,
            "    #[sysml::refines(client = \"{}\", supplier = \"{}\")]",
            escape_rust_str(&rf.client),
            escape_rust_str(&rf.supplier)
        );
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if r.attributes.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for a in &r.attributes {
            emit_rust_attr_field(a, &mut used, out);
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

fn emit_rust_specification(
    ru: &RequirementUsage,
    global_defs: &BTreeMap<String, (String, String, DefCategory)>,
    out: &mut String,
) {
    let rname = to_pascal_ident(&ru.name);
    emit_doc_comments(&ru.doc, "    ", out);
    let _ = writeln!(
        out,
        "    #[sysml::specification(name = \"{}\")]",
        escape_rust_str(&ru.name)
    );
    if let Some(subj) = &ru.subject {
        let st = rust_type_for_sysml(&subj.type_name, global_defs);
        let _ = writeln!(
            out,
            "    #[sysml::subject(name = \"{}\", ty = {st})]",
            escape_rust_str(&subj.name)
        );
    }
    // Map nested requirement usage names -> their ReqDef types so `satisfy 'clr-R050' by ...`
    // can compile-time check against the actual RequirementDef struct!
    let mut nested_req_types: BTreeMap<String, String> = BTreeMap::new();
    for n in &ru.nested_requirements {
        if let Some(ty) = &n.type_name {
            nested_req_types.insert(n.name.clone(), rust_type_for_sysml(ty, global_defs));
        }
    }
    for sat in &ru.satisfies {
        let req_ty = nested_req_types
            .get(&sat.requirement)
            .cloned()
            .unwrap_or_else(|| rust_type_for_sysml(&sat.requirement, global_defs));
        let mut parts = vec![
            format!("req = {req_ty}"),
            format!("requirement = \"{}\"", escape_rust_str(&sat.requirement)),
        ];
        if let Some(by) = &sat.by {
            parts.push(format!("by = \"{}\"", escape_rust_str(by)));
        }
        if sat.asserted {
            parts.push("assert".to_string());
        }
        let _ = writeln!(out, "    #[sysml::satisfy({})]", parts.join(", "));
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if ru.nested_requirements.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for n in &ru.nested_requirements {
            let fname = unique_ident(&to_snake_ident(&n.name), &mut used);
            let rty = n
                .type_name
                .as_deref()
                .map(|t| rust_type_for_sysml(t, global_defs))
                .unwrap_or_else(|| "()".to_string());
            let _ = writeln!(
                out,
                "        #[sysml::requirement_ref(name = \"{}\")]",
                escape_rust_str(&n.name)
            );
            let _ = writeln!(out, "        pub {fname}: {rty},");
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

fn emit_rust_part_def(
    p: &PartDef,
    global_defs: &BTreeMap<String, (String, String, DefCategory)>,
    out: &mut String,
) {
    let rname = to_pascal_ident(&p.name);
    emit_doc_comments(&p.doc, "    ", out);

    let mut part_flags = Vec::new();
    if p.is_abstract {
        part_flags.push("abstract");
    }
    if p.is_individual {
        part_flags.push("individual");
    }
    if part_flags.is_empty() {
        let _ = writeln!(out, "    #[sysml::part]");
    } else {
        let _ = writeln!(out, "    #[sysml::part({})]", part_flags.join(", "));
    }
    if rname != p.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&p.name));
    }
    if !p.specializes.is_empty() {
        let specs = p
            .specializes
            .iter()
            .map(|sp| rust_type_for_sysml(sp, global_defs))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    #[sysml::specializes({specs})]");
    }
    for perf in &p.performs {
        if let (Some(pname), Some(atype)) = (&perf.name, &perf.action_type) {
            let rfield = to_snake_ident(pname);
            let ract = rust_type_for_sysml(atype, global_defs);
            let _ = writeln!(
                out,
                "    #[sysml::perform({rfield}: {ract}, name = \"{}\")]",
                escape_rust_str(pname)
            );
        }
    }
    for sat in &p.satisfies {
        let req_ty = rust_type_for_sysml(&sat.requirement, global_defs);
        let mut parts = vec![format!("req = {req_ty}")];
        if let Some(by) = &sat.by {
            parts.push(format!("by = \"{}\"", escape_rust_str(by)));
        }
        let _ = writeln!(out, "    #[sysml::satisfy({})]", parts.join(", "));
    }
    for st in &p.exhibit_states {
        if let Some(sty) = &st.type_name {
            let rst = rust_type_for_sysml(sty, global_defs);
            let _ = writeln!(
                out,
                "    #[sysml::exhibit(name = \"{}\", state = {rst})]",
                escape_rust_str(&st.name)
            );
        }
    }

    for c in &p.comments {
        if let Some(cname) = &c.name {
            let _ = writeln!(
                out,
                "    #[sysml::comment(name = \"{}\", body = \"{}\")]",
                escape_rust_str(cname),
                escape_rust_str(&c.body)
            );
        } else {
            let _ = writeln!(
                out,
                "    #[sysml::comment(\"{}\")]",
                escape_rust_str(&c.body)
            );
        }
    }
    for rf in &p.refinements {
        let _ = writeln!(
            out,
            "    #[sysml::refines(client = \"{}\", supplier = \"{}\")]",
            escape_rust_str(&rf.client),
            escape_rust_str(&rf.supplier)
        );
    }

    // Emit `#[sysml::connect(...)]` for interface/connection usages with `from` & `to`
    for conn in &p.connections {
        if let (Some(from), Some(to)) = (&conn.from, &conn.to) {
            let from_rust = sysml_chain_to_rust_chain(from);
            let to_rust = sysml_chain_to_rust_chain(to);
            let mut parts = Vec::new();
            if conn.kind == ConnectionKind::Interface {
                if let Some(ty) = &conn.type_name {
                    parts.push(format!("interface = {}", rust_type_for_sysml(ty, global_defs)));
                }
            } else if let Some(ty) = &conn.type_name {
                parts.push(format!("connection = \"{}\"", escape_rust_str(ty)));
            }
            if let Some(cname) = &conn.name {
                parts.push(format!("name = \"{}\"", escape_rust_str(cname)));
            }
            parts.push(format!("from = {from_rust}"));
            parts.push(format!("to = {to_rust}"));
            parts.push(format!("from_sysml = \"{}\"", escape_rust_str(from)));
            parts.push(format!("to_sysml = \"{}\"", escape_rust_str(to)));
            let _ = writeln!(out, "    #[sysml::connect({})]", parts.join(", "));
        }
    }

    let has_fields = !p.attributes.is_empty()
        || !p.parts.is_empty()
        || !p.ports.is_empty()
        || !p.items.is_empty()
        || !p.requirements.is_empty();

    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if !has_fields {
        let _ = writeln!(out, "    pub struct {rname};");
        out.push('\n');
        return;
    }

    let _ = writeln!(out, "    pub struct {rname} {{");
    let mut used = BTreeSet::new();
    for a in &p.attributes {
        emit_rust_attr_field(a, &mut used, out);
    }
    for sub in &p.parts {
        let base_field = sub
            .name
            .as_deref()
            .or_else(|| sub.redefines.first().map(|s| s.as_str()))
            .unwrap_or("part");
        let fname = unique_ident(&to_snake_ident(base_field), &mut used);
        let mut opts = Vec::new();
        if let Some(raw_name) = &sub.name {
            opts.push(format!("name = \"{}\"", escape_rust_str(raw_name)));
        } else {
            opts.push("anonymous".to_string());
        }
        if let Some(m) = &sub.multiplicity {
            opts.push(format!("mult = \"{}\"", m.render()));
        }
        if sub.is_ordered {
            opts.push("ordered".to_string());
        }
        if sub.is_individual {
            opts.push("individual".to_string());
        }
        if sub.is_ref {
            opts.push("ref".to_string());
        }
        for s in &sub.subsets {
            opts.push(format!("subsets = \"{}\"", escape_rust_str(s)));
        }
        for r in &sub.redefines {
            opts.push(format!("redefines = \"{}\"", escape_rust_str(r)));
        }
        if let Some(def) = &sub.default_value {
            opts.push(format!("default = \"{}\"", escape_rust_str(def)));
        }
        let is_many = sub
            .multiplicity
            .as_ref()
            .map(|m| m.upper == "*" || m.lower.is_some())
            .unwrap_or(false);
        let rty = if let Some(first_ty) = sub.type_names.first() {
            let base = rust_type_for_sysml(first_ty, global_defs);
            if sub.type_names.len() > 1 {
                opts.push(format!("ty = \"{}\"", escape_rust_str(&sub.type_names.join(", "))));
            } else if base != *first_ty {
                opts.push(format!("ty = \"{}\"", escape_rust_str(first_ty)));
            }
            if is_many {
                format!("Vec<{base}>")
            } else if base == rname {
                format!("Box<{base}>")
            } else {
                base
            }
        } else {
            opts.push("untyped".to_string());
            opts.push("ty = \"\"".to_string());
            "Vec<()>".to_string()
        };
        let _ = writeln!(out, "        #[sysml::part({})]", opts.join(", "));
        let _ = writeln!(out, "        pub {fname}: {rty},");
    }
    for port in &p.ports {
        let fname = unique_ident(&to_snake_ident(&port.name), &mut used);
        let base_ty = rust_type_for_sysml(&port.type_name, global_defs);
        let rty = if port.conjugated {
            format!("Conjugated<{base_ty}>")
        } else {
            base_ty
        };
        let _ = writeln!(
            out,
            "        #[sysml::port(name = \"{}\")]",
            escape_rust_str(&port.name)
        );
        let _ = writeln!(out, "        pub {fname}: {rty},");
    }
    for it in &p.items {
        let fname = unique_ident(&to_snake_ident(&it.name), &mut used);
        let base_ty = rust_type_for_sysml(&it.type_name, global_defs);
        let rty = if it.multiplicity.is_some() {
            format!("Vec<{base_ty}>")
        } else {
            base_ty
        };
        let mut iopts = vec![format!("name = \"{}\"", escape_rust_str(&it.name))];
        for s in &it.subsets {
            iopts.push(format!("subsets = \"{}\"", escape_rust_str(s)));
        }
        emit_doc_comments(&it.doc, "        ", out);
        let _ = writeln!(out, "        #[sysml::item({})]", iopts.join(", "));
        let _ = writeln!(out, "        pub {fname}: {rty},");
    }
    for req in &p.requirements {
        let fname = unique_ident(&to_snake_ident(&req.name), &mut used);
        let mut opts = vec![format!("name = \"{}\"", escape_rust_str(&req.name))];
        if let Some(m) = &req.multiplicity {
            opts.push(format!("mult = \"{}\"", m.render()));
        }
        for s in &req.subsets {
            opts.push(format!("subsets = \"{}\"", escape_rust_str(s)));
        }
        let base_ty = req
            .type_name
            .as_deref()
            .map(|t| rust_type_for_sysml(t, global_defs))
            .unwrap_or_else(|| "()".to_string());
        let rty = if req.multiplicity.is_some() {
            format!("Vec<{base_ty}>")
        } else {
            base_ty
        };
        emit_doc_comments(&req.doc, "        ", out);
        let _ = writeln!(out, "        #[sysml::requirement_ref({})]", opts.join(", "));
        let _ = writeln!(out, "        pub {fname}: {rty},");
    }
    let _ = writeln!(out, "    }}");
    out.push('\n');
}

