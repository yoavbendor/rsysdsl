//! IR -> idiomatic, compilable Rust DSL (`#[sysml::*]`) source code generator.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use sysml_ir::*;

/// Configuration options for generating Rust DSL source code from a lifted IR `Model`.
#[derive(Debug, Clone)]
pub struct CodegenOptions {
    /// Emit a `pub fn sysml_model() -> sysml_ir::Model` aggregator at the module root.
    pub emit_model_fn: bool,
    /// Emit a `main()` that prints the re-emitted `.sysml` text to stdout (useful for
    /// standalone `rustc` / `cargo run` round-trip verification).
    pub emit_main_emitter: bool,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            emit_model_fn: true,
            emit_main_emitter: false,
        }
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
    "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true",
    "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final",
    "macro", "override", "priv", "try", "typeof", "unsized", "virtual", "yield",
];

fn to_snake_ident(raw: &str) -> String {
    let mut out = String::new();
    let mut prev_lower_or_digit = false;
    for ch in raw.chars() {
        if ch.is_ascii_alphanumeric() {
            if ch.is_ascii_uppercase() && prev_lower_or_digit {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
            prev_lower_or_digit = ch.is_ascii_lowercase() || ch.is_ascii_digit();
        } else {
            if !out.is_empty() && !out.ends_with('_') {
                out.push('_');
            }
            prev_lower_or_digit = false;
        }
    }
    let out = out.trim_matches('_').to_string();
    let mut ident = if out.is_empty() {
        "unnamed".to_string()
    } else if out.chars().next().unwrap().is_ascii_digit() {
        format!("_{out}")
    } else {
        out
    };
    if RUST_KEYWORDS.contains(&ident.as_str()) {
        ident.push('_');
    }
    ident
}

fn to_pascal_ident(raw: &str) -> String {
    let mut out = String::new();
    let mut upper_next = true;
    for ch in raw.chars() {
        if ch.is_ascii_alphanumeric() {
            if upper_next {
                out.push(ch.to_ascii_uppercase());
                upper_next = false;
            } else {
                out.push(ch);
            }
        } else {
            upper_next = true;
        }
    }
    let mut ident = if out.is_empty() {
        "Unnamed".to_string()
    } else if out.chars().next().unwrap().is_ascii_digit() {
        format!("N{out}")
    } else {
        out
    };
    if RUST_KEYWORDS.contains(&ident.as_str()) {
        ident.push('_');
    }
    ident
}

fn escape_rust_str(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

fn emit_doc_comments(doc: &Option<String>, indent: &str, out: &mut String) {
    if let Some(d) = doc {
        for line in d.lines() {
            let _ = writeln!(out, "{indent}/// {}", line.trim());
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum DefCategory {
    Part,
    Port,
    Interface,
    Connection,
    Item,
    Enum,
    Action,
    State,
    Requirement,
}

/// Generate clean, compilable Rust DSL source code from a lifted `sysml_ir::Model`.
pub fn generate_rust_dsl(model: &Model, opts: &CodegenOptions) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Auto-generated by `sysml-lift` from SysML v2 source."
    );
    let _ = writeln!(
        out,
        "#![allow(dead_code, unused_imports, non_camel_case_types, clippy::all)]"
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "use sysml_dsl::prelude::*;");
    let _ = writeln!(out);

    // Index all known definitions across all lifted packages:
    // pkg_name -> { sysml_name -> (rust_ident, category) }
    let mut pkg_map: BTreeMap<String, String> = BTreeMap::new();
    let mut global_defs: BTreeMap<String, (String, String, DefCategory)> = BTreeMap::new();
    for pkg in &model.packages {
        let mod_name = to_snake_ident(&pkg.name);
        pkg_map.insert(pkg.name.clone(), mod_name.clone());
        for m in &pkg.members {
            let entry = match m {
                PackageMember::PartDef(p) => Some((&p.name, DefCategory::Part)),
                PackageMember::PortDef(p) => Some((&p.name, DefCategory::Port)),
                PackageMember::InterfaceDef(i) => Some((&i.name, DefCategory::Interface)),
                PackageMember::ConnectionDef(c) => Some((&c.name, DefCategory::Connection)),
                PackageMember::ItemDef(i) => Some((&i.name, DefCategory::Item)),
                PackageMember::EnumDef(e) => Some((&e.name, DefCategory::Enum)),
                PackageMember::ActionDef(a) => Some((&a.name, DefCategory::Action)),
                PackageMember::StateDef(s) => Some((&s.name, DefCategory::State)),
                PackageMember::RequirementDef(r) => Some((&r.name, DefCategory::Requirement)),
                _ => None,
            };
            if let Some((sysml_name, cat)) = entry {
                global_defs.insert(
                    sysml_name.clone(),
                    (mod_name.clone(), to_pascal_ident(sysml_name), cat),
                );
            }
        }
    }

    // Collect external base/reference types not defined in the lifted model so
    // generated code still compiles cleanly when lifting partial slices (e.g. OMG `StateAction`).
    let mut external_stubs: BTreeMap<String, DefCategory> = BTreeMap::new();
    for pkg in &model.packages {
        collect_external_refs(pkg, &global_defs, &mut external_stubs);
    }

    if !external_stubs.is_empty() {
        let _ = writeln!(out, "/// Standard library / external reference stubs for standalone compilation.");
        let _ = writeln!(out, "pub mod external_stubs {{");
        let _ = writeln!(out, "    use sysml_dsl::prelude::*;");
        for (name, cat) in &external_stubs {
            let rname = to_pascal_ident(name);
            let macro_attr = match cat {
                DefCategory::Part => "#[sysml::part(abstract)]",
                DefCategory::Port => "#[sysml::port]",
                DefCategory::Item => "#[sysml::item]",
                DefCategory::Action => "#[sysml::action(abstract)]",
                DefCategory::State => "#[sysml::state(abstract)]",
                DefCategory::Requirement => "#[sysml::requirement(abstract)]",
                _ => "#[sysml::part(abstract)]",
            };
            let _ = writeln!(out, "    {macro_attr}");
            if rname != *name {
                let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(name));
            }
            let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
            let _ = writeln!(out, "    pub struct {rname};");
        }
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
    }

    for pkg in &model.packages {
        emit_rust_package(
            pkg,
            &pkg_map,
            &global_defs,
            !external_stubs.is_empty(),
            &mut out,
        );
        out.push('\n');
    }

    if opts.emit_model_fn {
        let _ = writeln!(out, "/// Builds the complete `sysml_ir::Model` from all lifted packages.");
        let _ = writeln!(out, "pub fn sysml_model() -> ::sysml_ir::Model {{");
        let _ = writeln!(out, "    ::sysml_ir::Model::new(vec![");
        for pkg in &model.packages {
            let mod_name = to_snake_ident(&pkg.name);
            let _ = writeln!(out, "        {mod_name}::sysml_package(),");
        }
        let _ = writeln!(out, "    ])");
        let _ = writeln!(out, "}}");
    }

    if opts.emit_main_emitter {
        let _ = writeln!(out);
        let _ = writeln!(out, "fn main() {{");
        let _ = writeln!(out, "    let text = ::sysml_emit::emit_model(&sysml_model());");
        let _ = writeln!(out, "    print!(\"{{text}}\");");
        let _ = writeln!(out, "}}");
    }

    out
}

fn collect_external_refs(
    pkg: &Package,
    global_defs: &BTreeMap<String, (String, String, DefCategory)>,
    stubs: &mut BTreeMap<String, DefCategory>,
) {
    let mut check = |raw: &str, cat: DefCategory| {
        let simple = raw.rsplit("::").next().unwrap_or(raw).trim();
        if simple.is_empty()
            || matches!(
                simple,
                "Real" | "Integer" | "Boolean" | "String" | "RatioValue" | "Natural"
            )
        {
            return;
        }
        if !global_defs.contains_key(simple) {
            stubs.entry(simple.to_string()).or_insert(cat);
        }
    };

    for m in &pkg.members {
        match m {
            PackageMember::PartDef(p) => {
                for s in &p.specializes {
                    check(s, DefCategory::Part);
                }
                for sub in &p.parts {
                    for t in &sub.type_names {
                        check(t, DefCategory::Part);
                    }
                }
                for port in &p.ports {
                    check(&port.type_name, DefCategory::Port);
                }
                for it in &p.items {
                    check(&it.type_name, DefCategory::Item);
                }
                for perf in &p.performs {
                    if let Some(at) = &perf.action_type {
                        check(at, DefCategory::Action);
                    }
                }
                for r in &p.requirements {
                    if let Some(rt) = &r.type_name {
                        check(rt, DefCategory::Requirement);
                    }
                }
                for st in &p.exhibit_states {
                    if let Some(st_ty) = &st.type_name {
                        check(st_ty, DefCategory::State);
                    }
                }
            }
            PackageMember::PortDef(p) => {
                for s in &p.specializes {
                    check(s, DefCategory::Port);
                }
                for it in &p.items {
                    check(&it.type_name, DefCategory::Item);
                }
            }
            PackageMember::InterfaceDef(i) => {
                for e in &i.ends {
                    check(&e.type_name, DefCategory::Port);
                }
            }
            PackageMember::ActionDef(a) => {
                for s in &a.specializes {
                    check(s, DefCategory::Action);
                }
                for p in &a.params {
                    check(&p.type_name, DefCategory::Item);
                }
            }
            PackageMember::StateDef(s) => {
                for sp in &s.specializes {
                    check(sp, DefCategory::State);
                }
                if let Some(da) = &s.do_action {
                    for step in &da.steps {
                        if let Some(st) = &step.type_name {
                            check(st, DefCategory::Action);
                        }
                    }
                }
            }
            PackageMember::RequirementDef(r) => {
                for sp in &r.specializes {
                    check(sp, DefCategory::Requirement);
                }
                if let Some(subj) = &r.subject {
                    check(&subj.type_name, DefCategory::Part);
                }
            }
            PackageMember::RequirementUsage(ru) => {
                if let Some(subj) = &ru.subject {
                    check(&subj.type_name, DefCategory::Part);
                }
                for n in &ru.nested_requirements {
                    if let Some(rt) = &n.type_name {
                        check(rt, DefCategory::Requirement);
                    }
                }
            }
            _ => {}
        }
    }
}

fn emit_rust_package(
    pkg: &Package,
    pkg_map: &BTreeMap<String, String>,
    global_defs: &BTreeMap<String, (String, String, DefCategory)>,
    has_stubs: bool,
    out: &mut String,
) {
    let mod_name = to_snake_ident(&pkg.name);
    emit_doc_comments(&pkg.doc, "", out);
    if pkg.is_library {
        let _ = writeln!(
            out,
            "#[sysml::package(library, name = \"{}\")]",
            escape_rust_str(&pkg.name)
        );
    } else {
        let _ = writeln!(
            out,
            "#[sysml::package(name = \"{}\")]",
            escape_rust_str(&pkg.name)
        );
    }
    for c in &pkg.comments {
        if let Some(cname) = &c.name {
            let _ = writeln!(
                out,
                "#[sysml::comment(name = \"{}\", body = \"{}\")]",
                escape_rust_str(cname),
                escape_rust_str(&c.body)
            );
        } else {
            let _ = writeln!(out, "#[sysml::comment(\"{}\")]", escape_rust_str(&c.body));
        }
    }
    for imp in &pkg.imports {
        let suffix = match imp.wildcard {
            ImportWildcard::None => "",
            ImportWildcard::Star => "::*",
            ImportWildcard::RecursiveStar => "::**",
        };
        let _ = writeln!(
            out,
            "#[sysml::import(\"{}{suffix}\")]",
            escape_rust_str(&imp.target)
        );
    }
    let _ = writeln!(out, "pub mod {mod_name} {{");
    let _ = writeln!(out, "    use sysml_dsl::prelude::*;");
    if has_stubs {
        let _ = writeln!(out, "    use super::external_stubs::*;");
    }

    // Bring imported sibling packages into Rust scope
    let mut brought_in = BTreeSet::new();
    for imp in &pkg.imports {
        let root_pkg = imp.target.split("::").next().unwrap_or(&imp.target);
        if let Some(target_mod) = pkg_map.get(root_pkg) {
            if target_mod != &mod_name && brought_in.insert(target_mod.clone()) {
                let _ = writeln!(out, "    use super::{target_mod}::*;");
            }
        }
    }
    // Also bring in any sibling package referenced via qualified name
    for (_, (target_mod, _, _)) in global_defs {
        if target_mod != &mod_name && brought_in.insert(target_mod.clone()) {
            let _ = writeln!(out, "    use super::{target_mod}::*;");
        }
    }
    out.push('\n');

    // Track local names in this package to avoid duplicate Rust struct definitions
    let mut local_names = BTreeSet::new();
    for m in &pkg.members {
        match m {
            PackageMember::ItemDef(i) => {
                if local_names.insert(to_pascal_ident(&i.name)) {
                    emit_rust_item_def(i, out);
                }
            }
            PackageMember::EnumDef(e) => {
                if local_names.insert(to_pascal_ident(&e.name)) {
                    emit_rust_enum_def(e, out);
                }
            }
            PackageMember::PortDef(p) => {
                if local_names.insert(to_pascal_ident(&p.name)) {
                    emit_rust_port_def(p, out);
                }
            }
            PackageMember::InterfaceDef(i) => {
                if local_names.insert(to_pascal_ident(&i.name)) {
                    emit_rust_interface_def(i, out);
                }
            }
            PackageMember::ConnectionDef(c) => {
                if local_names.insert(to_pascal_ident(&c.name)) {
                    emit_rust_connection_def(c, out);
                }
            }
            PackageMember::ActionDef(a) => {
                if local_names.insert(to_pascal_ident(&a.name)) {
                    emit_rust_action_def(a, out);
                }
            }
            PackageMember::StateDef(s) => {
                if local_names.insert(to_pascal_ident(&s.name)) {
                    emit_rust_state_def(s, out);
                }
            }
            PackageMember::RequirementDef(r) => {
                if local_names.insert(to_pascal_ident(&r.name)) {
                    emit_rust_requirement_def(r, out);
                }
            }
            PackageMember::RequirementUsage(ru) => {
                if local_names.insert(to_pascal_ident(&ru.name)) {
                    emit_rust_specification(ru, global_defs, out);
                }
            }
            PackageMember::PartDef(p) => {
                if local_names.insert(to_pascal_ident(&p.name)) {
                    emit_rust_part_def(p, global_defs, out);
                }
            }
            PackageMember::CalcDef(c) => {
                if local_names.insert(to_pascal_ident(&c.name)) {
                    emit_rust_calc_def(c, out);
                }
            }
            PackageMember::AnalysisDef(a) => {
                if local_names.insert(to_pascal_ident(&a.name)) {
                    emit_rust_analysis_def(a, out);
                }
            }
            PackageMember::AnalysisUsage(a) => {
                if local_names.insert(to_pascal_ident(&a.name)) {
                    emit_rust_analysis_usage(a, out);
                }
            }
            _ => {}
        }
    }

    let _ = writeln!(out, "}}");
}

fn rust_type_for_sysml(raw: &str, global_defs: &BTreeMap<String, (String, String, DefCategory)>) -> String {
    let simple = raw.rsplit("::").next().unwrap_or(raw).trim();
    match simple {
        "Real" | "RatioValue" => "f64".to_string(),
        "Integer" | "Natural" => "i64".to_string(),
        "Boolean" => "bool".to_string(),
        "String" => "String".to_string(),
        other => {
            if let Some((_, rident, _)) = global_defs.get(other) {
                rident.clone()
            } else {
                to_pascal_ident(other)
            }
        }
    }
}

fn emit_rust_item_def(i: &ItemDef, out: &mut String) {
    let rname = to_pascal_ident(&i.name);
    emit_doc_comments(&i.doc, "    ", out);
    if i.is_abstract {
        let _ = writeln!(out, "    #[sysml::item(abstract)]");
    } else {
        let _ = writeln!(out, "    #[sysml::item]");
    }
    if rname != i.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&i.name));
    }
    if !i.specializes.is_empty() {
        let specs = i
            .specializes
            .iter()
            .map(|s| to_pascal_ident(s.rsplit("::").next().unwrap_or(s)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    #[sysml::specializes({specs})]");
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if i.attributes.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for a in &i.attributes {
            emit_rust_attr_field(a, &mut used, out);
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

fn emit_rust_enum_def(e: &EnumDef, out: &mut String) {
    let rname = to_pascal_ident(&e.name);
    emit_doc_comments(&e.doc, "    ", out);
    let _ = writeln!(out, "    #[sysml::enum_def]");
    if rname != e.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&e.name));
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    let _ = writeln!(out, "    pub enum {rname} {{");
    for v in &e.variants {
        let rv = to_pascal_ident(v);
        let _ = writeln!(out, "        #[sysml::name = \"{}\"]", escape_rust_str(v));
        let _ = writeln!(out, "        {rv},");
    }
    let _ = writeln!(out, "    }}");
    out.push('\n');
}

fn emit_rust_port_def(p: &PortDef, out: &mut String) {
    let rname = to_pascal_ident(&p.name);
    emit_doc_comments(&p.doc, "    ", out);
    if p.is_symmetric {
        let _ = writeln!(out, "    #[sysml::port(symmetric)]");
    } else {
        let _ = writeln!(out, "    #[sysml::port]");
    }
    if rname != p.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&p.name));
    }
    if !p.specializes.is_empty() {
        let specs = p
            .specializes
            .iter()
            .map(|s| to_pascal_ident(s.rsplit("::").next().unwrap_or(s)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    #[sysml::specializes({specs})]");
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if p.items.is_empty() && p.attributes.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for it in &p.items {
            let fname = unique_ident(&to_snake_ident(&it.name), &mut used);
            match it.direction {
                Some(Direction::In) => {
                    let _ = writeln!(out, "        #[sysml::in_item]");
                }
                Some(Direction::Out) => {
                    let _ = writeln!(out, "        #[sysml::out]");
                }
                Some(Direction::InOut) => {
                    let _ = writeln!(out, "        #[sysml::inout]");
                }
                None => {}
            }
            let _ = writeln!(
                out,
                "        #[sysml::name = \"{}\"]",
                escape_rust_str(&it.name)
            );
            let rty = to_pascal_ident(it.type_name.rsplit("::").next().unwrap_or(&it.type_name));
            let _ = writeln!(out, "        pub {fname}: {rty},");
        }
        for a in &p.attributes {
            emit_rust_attr_field(a, &mut used, out);
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

fn emit_rust_interface_def(i: &InterfaceDef, out: &mut String) {
    let rname = to_pascal_ident(&i.name);
    emit_doc_comments(&i.doc, "    ", out);
    let _ = writeln!(out, "    #[sysml::interface]");
    if rname != i.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&i.name));
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    let _ = writeln!(out, "    pub struct {rname} {{");
    let mut used = BTreeSet::new();
    for end in &i.ends {
        let fname = unique_ident(&to_snake_ident(&end.name), &mut used);
        let _ = writeln!(out, "        #[sysml::end]");
        let _ = writeln!(
            out,
            "        #[sysml::name = \"{}\"]",
            escape_rust_str(&end.name)
        );
        let base_ty = to_pascal_ident(end.type_name.rsplit("::").next().unwrap_or(&end.type_name));
        let rty = if end.conjugated {
            format!("Conjugated<{base_ty}>")
        } else {
            base_ty
        };
        let _ = writeln!(out, "        pub {fname}: {rty},");
    }
    let _ = writeln!(out, "    }}");
    out.push('\n');
}

fn emit_rust_connection_def(c: &ConnectionDef, out: &mut String) {
    let rname = to_pascal_ident(&c.name);
    emit_doc_comments(&c.doc, "    ", out);
    if c.is_abstract {
        let _ = writeln!(out, "    #[sysml::connection(abstract)]");
    } else {
        let _ = writeln!(out, "    #[sysml::connection]");
    }
    if rname != c.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&c.name));
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if c.ends.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for e in &c.ends {
            let fname = unique_ident(&to_snake_ident(&e.name), &mut used);
            let mut opts = vec![format!("kind = \"{}\"", escape_rust_str(&e.kind_keyword))];
            if let Some(m) = &e.multiplicity {
                opts.push(format!("mult = \"{}\"", m.render()));
            }
            for sub in &e.subsets {
                opts.push(format!("subsets = \"{}\"", escape_rust_str(sub)));
            }
            let _ = writeln!(out, "        #[sysml::end({})]", opts.join(", "));
            let _ = writeln!(
                out,
                "        #[sysml::name = \"{}\"]",
                escape_rust_str(&e.name)
            );
            let rty = to_pascal_ident(e.type_name.rsplit("::").next().unwrap_or(&e.type_name));
            let _ = writeln!(out, "        pub {fname}: {rty},");
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

fn emit_rust_action_def(a: &ActionDef, out: &mut String) {
    let rname = to_pascal_ident(&a.name);
    emit_doc_comments(&a.doc, "    ", out);
    if a.is_abstract {
        let _ = writeln!(out, "    #[sysml::action(abstract)]");
    } else {
        let _ = writeln!(out, "    #[sysml::action]");
    }
    if rname != a.name {
        let _ = writeln!(out, "    #[sysml::name = \"{}\"]", escape_rust_str(&a.name));
    }
    if !a.specializes.is_empty() {
        let specs = a
            .specializes
            .iter()
            .map(|s| to_pascal_ident(s.rsplit("::").next().unwrap_or(s)))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    #[sysml::specializes({specs})]");
    }
    for step in &a.steps {
        if let Some(st) = &step.type_name {
            let sty = to_pascal_ident(st.rsplit("::").next().unwrap_or(st));
            let _ = writeln!(out, "    #[sysml::step({}: {sty})]", step.name);
        }
    }
    for rf in &a.refinements {
        let _ = writeln!(
            out,
            "    #[sysml::refines(client = \"{}\", supplier = \"{}\")]",
            escape_rust_str(&rf.client),
            escape_rust_str(&rf.supplier)
        );
    }
    let _ = writeln!(out, "    #[derive(Debug, Clone, Default)]");
    if a.params.is_empty() {
        let _ = writeln!(out, "    pub struct {rname};");
    } else {
        let _ = writeln!(out, "    pub struct {rname} {{");
        let mut used = BTreeSet::new();
        for p in &a.params {
            let fname = unique_ident(&to_snake_ident(&p.name), &mut used);
            let dir_attr = match p.direction {
                Direction::In => "#[sysml::in_param]",
                Direction::Out => "#[sysml::out_param]",
                Direction::InOut => "#[sysml::inout_param]",
            };
            let _ = writeln!(out, "        {dir_attr}");
            let _ = writeln!(
                out,
                "        #[sysml::name = \"{}\"]",
                escape_rust_str(&p.name)
            );
            let rty = match p.type_name.as_str() {
                "Boolean" => "bool".to_string(),
                "Integer" => "i64".to_string(),
                "Real" => "f64".to_string(),
                "String" => "String".to_string(),
                other => to_pascal_ident(other.rsplit("::").next().unwrap_or(other)),
            };
            let _ = writeln!(out, "        pub {fname}: {rty},");
        }
        let _ = writeln!(out, "    }}");
    }
    out.push('\n');
}

