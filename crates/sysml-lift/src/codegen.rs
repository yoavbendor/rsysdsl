fn emit_rust_attr_field(a: &AttributeUsage, used: &mut BTreeSet<String>, out: &mut String) {
    let base_name = a
        .name
        .as_deref()
        .or_else(|| a.redefines.first().map(|s| s.as_str()))
        .or_else(|| a.subsets.first().map(|s| s.as_str()))
        .unwrap_or("attr");
    let fname = unique_ident(&to_snake_ident(base_name), used);

    let mut opts = Vec::new();
    if a.is_keywordless {
        opts.push("keywordless".to_string());
    }
    if let Some(n) = &a.name {
        opts.push(format!("name = \"{}\"", escape_rust_str(n)));
        if !a.redefines.is_empty() {
            opts.push("keep_name = \"true\"".to_string());
        }
    } else if !a.redefines.is_empty() {
        opts.push("anonymous".to_string());
    }
    if let Some(ty) = &a.type_name {
        opts.push(format!("ty = \"{}\"", escape_rust_str(ty)));
    }
    for sub in &a.subsets {
        opts.push(format!("subsets = \"{}\"", escape_rust_str(sub)));
    }
    for red in &a.redefines {
        opts.push(format!("redefines = \"{}\"", escape_rust_str(red)));
    }
    if let Some(val) = &a.value {
        match a.value_kind {
            ValueKind::Default => opts.push(format!("default = \"{}\"", escape_rust_str(val))),
            ValueKind::Initial => {
                opts.push("value_kind = \"initial\"".to_string());
                opts.push(format!("value = \"{}\"", escape_rust_str(val)));
            }
            ValueKind::DefaultInitial => {
                opts.push("value_kind = \"default_initial\"".to_string());
                opts.push(format!("value = \"{}\"", escape_rust_str(val)));
            }
            ValueKind::Bound => opts.push(format!("value = \"{}\"", escape_rust_str(val))),
        }
    }
    if let Some(unit) = &a.unit {
        opts.push(format!("unit = \"{}\"", escape_rust_str(unit)));
        if !is_checked_si_unit(unit) {
            opts.push("custom_unit".to_string());
        }
    }
    emit_doc_comments(&a.doc, "        ", out);
    if opts.is_empty() {
        let _ = writeln!(out, "        #[sysml::attr]");
    } else {
        let _ = writeln!(out, "        #[sysml::attr({})]", opts.join(", "));
    }

    let rust_ty = match a.type_name.as_deref() {
        Some("Integer") => "i64",
        Some("Boolean") => "bool",
        Some("String") => "String",
        _ => {
            if a.unit.is_some() || a.subsets.iter().any(|s| s.contains("ISQ::")) {
                "Quantity<f64>"
            } else {
                "f64"
            }
        }
    };
    let _ = writeln!(out, "        pub {fname}: {rust_ty},");
}

fn sysml_chain_to_rust_chain(chain: &str) -> String {
    chain
        .split('.')
        .map(to_snake_ident)
        .collect::<Vec<_>>()
        .join(".")
}

fn unique_ident(base: &str, used: &mut BTreeSet<String>) -> String {
    if used.insert(base.to_string()) {
        return base.to_string();
    }
    let mut i = 2usize;
    loop {
        let cand = format!("{base}_{i}");
        if used.insert(cand.clone()) {
            return cand;
        }
        i += 1;
    }
}

/// `true` if `unit` is accepted by the DSL's closed, OMG-resolvable SI unit table. Otherwise the
/// lifted attribute is marked `custom_unit` (a unit defined by the source model or another
/// library, e.g. `'%'`, `kN`, `SI::kg`), which opts out of the compile-time unit/dimension checks.
fn is_checked_si_unit(unit: &str) -> bool {
    matches!(
        sysml_core::units::check_unit(unit),
        sysml_core::units::UnitCheck::Ok(_)
    )
}
